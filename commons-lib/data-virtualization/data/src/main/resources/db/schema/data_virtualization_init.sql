CREATE TABLE IF NOT EXISTS vd_entity (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    entity_code VARCHAR(64) NOT NULL COMMENT '虚拟实体稳定编码',
    entity_name VARCHAR(128) NOT NULL COMMENT '虚拟实体名称',
    description VARCHAR(512) DEFAULT NULL COMMENT '说明',
    status INT NOT NULL DEFAULT 0 COMMENT '0草稿 1已发布 2已停用',
    catalog_version BIGINT NOT NULL DEFAULT 0 COMMENT '目录发布版本',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_entity_code (entity_code),
    KEY idx_vd_entity_status (status, enabled)
) COMMENT='虚拟实体';

CREATE TABLE IF NOT EXISTS vd_field (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    entity_id BIGINT NOT NULL COMMENT '虚拟实体ID',
    field_code VARCHAR(64) NOT NULL COMMENT '虚拟字段稳定编码',
    field_name VARCHAR(128) NOT NULL COMMENT '字段名称',
    logical_type INT NOT NULL COMMENT '标准逻辑类型',
    nullable BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否可空',
    primary_key BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否虚拟主键',
    ordinal_position INT NOT NULL DEFAULT 0 COMMENT '字段顺序',
    default_value VARCHAR(512) DEFAULT NULL COMMENT '默认值',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
    remark VARCHAR(512) DEFAULT NULL COMMENT '备注',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_field (entity_id, field_code),
    KEY idx_vd_field_entity (entity_id, enabled)
) COMMENT='虚拟字段';

CREATE TABLE IF NOT EXISTS vd_binding (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    entity_id BIGINT NOT NULL COMMENT '虚拟实体ID',
    binding_code VARCHAR(64) NOT NULL COMMENT '绑定稳定编码',
    binding_group VARCHAR(64) NOT NULL COMMENT '分片与副本组编码',
    binding_role INT NOT NULL DEFAULT 0 COMMENT '0主绑定 1副本',
    physical_table_meta_id BIGINT NOT NULL COMMENT '物理表元数据ID',
    source_key VARCHAR(64) NOT NULL COMMENT '数据源标识',
    physical_table_name VARCHAR(128) NOT NULL COMMENT '真实表名快照',
    readable BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否可读',
    writable BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否可写',
    read_weight INT NOT NULL DEFAULT 100 COMMENT '读取权重',
    write_priority INT NOT NULL DEFAULT 0 COMMENT '写优先级',
    routing_config JSON DEFAULT NULL COMMENT '强类型路由配置',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
    remark VARCHAR(512) DEFAULT NULL COMMENT '备注',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_binding (entity_id, binding_code),
    KEY idx_vd_binding_entity (entity_id, enabled),
    KEY idx_vd_binding_physical (source_key, physical_table_name)
) COMMENT='虚拟实体物理绑定';

CREATE TABLE IF NOT EXISTS vd_field_transform_rule (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    binding_id BIGINT NOT NULL COMMENT '物理绑定ID',
    rule_code VARCHAR(64) NOT NULL COMMENT '规则稳定编码',
    rule_name VARCHAR(128) NOT NULL COMMENT '规则名称',
    transform_mode INT NOT NULL COMMENT '0只读 1只写 2双向',
    read_transformer_code VARCHAR(64) DEFAULT NULL COMMENT '读取变换器编码',
    read_transformer_version INT DEFAULT NULL COMMENT '读取变换器版本',
    write_transformer_code VARCHAR(64) DEFAULT NULL COMMENT '写回变换器编码',
    write_transformer_version INT DEFAULT NULL COMMENT '写回变换器版本',
    read_config JSON DEFAULT NULL COMMENT '强类型读取配置',
    write_config JSON DEFAULT NULL COMMENT '强类型写回配置',
    script_code TEXT DEFAULT NULL COMMENT 'Python-like字段转换脚本',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
    remark VARCHAR(512) DEFAULT NULL COMMENT '备注',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_transform_rule (binding_id, rule_code),
    KEY idx_vd_transform_rule_binding (binding_id, enabled)
) COMMENT='字段变换规则';

CREATE TABLE IF NOT EXISTS vd_field_transform_port (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    rule_id BIGINT NOT NULL COMMENT '字段变换规则ID',
    field_side INT NOT NULL COMMENT '0物理字段 1虚拟字段',
    port_code VARCHAR(64) NOT NULL COMMENT '规则内端口编码',
    virtual_field_id BIGINT DEFAULT NULL COMMENT '虚拟字段ID',
    physical_field_meta_id BIGINT DEFAULT NULL COMMENT '物理字段元数据ID',
    physical_column_name VARCHAR(128) DEFAULT NULL COMMENT '物理字段名快照',
    ordinal_position INT NOT NULL DEFAULT 0 COMMENT '端口顺序',
    required_on_write BOOLEAN NOT NULL DEFAULT FALSE COMMENT '写回时是否必填',
    remark VARCHAR(512) DEFAULT NULL COMMENT '备注',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_transform_port (rule_id, field_side, port_code),
    KEY idx_vd_transform_port_virtual (virtual_field_id),
    KEY idx_vd_transform_port_physical (physical_field_meta_id)
) COMMENT='字段变换端口';

CREATE TABLE IF NOT EXISTS vd_relation (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    relation_code VARCHAR(64) NOT NULL COMMENT '源实体内关系编码',
    relation_name VARCHAR(128) NOT NULL COMMENT '关系名称',
    relation_result_mode TINYINT NOT NULL DEFAULT 0 COMMENT '关联结果形态：0=对象，1=集合',
    source_entity_id BIGINT NOT NULL COMMENT '源虚拟实体ID',
    source_field_id BIGINT NOT NULL COMMENT '源虚拟字段ID',
    target_entity_id BIGINT NOT NULL COMMENT '目标虚拟实体ID',
    target_field_id BIGINT NOT NULL COMMENT '目标虚拟字段ID',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
    remark VARCHAR(512) DEFAULT NULL COMMENT '备注',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建者',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新者',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    UNIQUE KEY uk_vd_relation_mapping (source_entity_id, relation_code, source_field_id),
    KEY idx_vd_relation_source (source_entity_id, enabled),
    KEY idx_vd_relation_target (target_entity_id, enabled)
) COMMENT='虚拟实体关系字段映射';
